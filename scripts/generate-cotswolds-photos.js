const fs = require('fs');
const path = require('path');

const PHOTO_DIR_FS = path.join(
  process.cwd(),
  'public/photos/listings/Cotswolds Luxury Retreat'
);
const PHOTO_BASE = '/photos/listings/Cotswolds Luxury Retreat';
const COVER_FILENAME = '224A8292.jpg';
const PINNED_GALLERY_COUNT = 6;
const IMAGE_EXT = /\.(jpe?g|png|webp|gif)$/i;
const OUT = path.join(process.cwd(), 'src/config/cotswoldsPhotos.ts');

function seededShuffle(items, seed) {
  const shuffled = [...items];
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = (Math.imul(31, hash) + seed.charCodeAt(i)) | 0;
  }
  for (let i = shuffled.length - 1; i > 0; i--) {
    hash = (Math.imul(1664525, hash) + 1013904223) | 0;
    const j = (hash >>> 0) % (i + 1);
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
}

function discoverCotswoldsPhotos() {
  if (!fs.existsSync(PHOTO_DIR_FS)) return [];
  const files = fs.readdirSync(PHOTO_DIR_FS).filter((f) => IMAGE_EXT.test(f));
  const sortedRest = files
    .filter((f) => f !== COVER_FILENAME)
    .sort((a, b) => a.localeCompare(b));
  const pinned = [COVER_FILENAME, ...sortedRest.slice(0, PINNED_GALLERY_COUNT - 1)];
  const remaining = sortedRest.slice(PINNED_GALLERY_COUNT - 1);
  const mixedRest = seededShuffle(remaining, 'cotswolds-soho-farm-house-gallery');
  return [...pinned, ...mixedRest].map((f) => `${PHOTO_BASE}/${f}`);
}

const photos = discoverCotswoldsPhotos();
const hero = `${PHOTO_BASE}/${COVER_FILENAME}`;

const contents = `/** Auto-generated by scripts/generate-cotswolds-photos.js — do not edit manually. */
export const HERO_PHOTO = ${JSON.stringify(hero)};
export const GALLERY_PHOTOS: string[] = ${JSON.stringify(photos, null, 2)};
`;

fs.writeFileSync(OUT, contents);
console.log(`Wrote ${photos.length} photos to ${OUT}`);
